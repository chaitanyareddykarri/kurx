/// Server actions are the only path from the browser to the chat API.
///
/// The session token lives in an httpOnly cookie and stays there: every REST call is made here,
/// server-side. The one place the token is handed to client JS is `/api/realtime-token`, and that
/// copy is used solely to open the SignalR connection (D-109) — never for REST.

export async function fetchMyChatsAction(archived = false): Promise<MyChat[]> {
  const session = await requireSession();
  return listMyChats(session.accessToken, archived);
}

/// Keyed on the ROOM id (D-292), so a direct room resolves through the same path an event room does.
export async function fetchRoomAction(roomId: string): Promise<ChatRoom> {
  const session = await requireSession();
  return getChatRoomById(session.accessToken, roomId);
}

