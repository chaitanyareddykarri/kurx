// ── Attachments ───────────────────────────────────────────────────────────────────────────
// Presign and confirm run here so the session token never reaches the browser. The PUT in between
// deliberately does NOT: it goes browser-direct to the presigned URL, because that URL carries its
// own signature and must not receive cookies, an Authorization header, or any interceptor.

